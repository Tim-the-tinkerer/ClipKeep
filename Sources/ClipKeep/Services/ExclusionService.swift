import AppKit
import Foundation

/// Decides whether a pasteboard snapshot should be recorded.
///
/// Password managers and other secret-bearing apps are excluded via:
/// 1. Standard NSPASTEBOARD concealed / transient pasteboard types
/// 2. Frontmost (source) application bundle identifier allow-list of exclusions
/// 3. Optional heuristic patterns for common secret paste types
enum ExclusionService {
    // MARK: - Public pasteboard type strings (NSPASTEBOARD convention)

    /// Content marked secret; password managers set this so history tools skip it.
    static let concealedType = "org.nspasteboard.ConcealedType"
    /// Short-lived paste; often used for one-time secrets.
    static let transientType = "org.nspasteboard.TransientType"
    /// Auto-clear after paste (related convention).
    static let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"
    /// Some apps use this for password fields.
    static let sourceAppType = "org.nspasteboard.source"

    /// Additional types commonly used by password managers / secure paste.
    private static let sensitiveTypeHints: [String] = [
        concealedType,
        transientType,
        autoGeneratedType,
        "com.agilebits.onepassword",
        "com.1password.item",
        "com.bitwarden.clipboard",
        "com.lastpass.clipboard",
        "com.dashlane.clipboard",
        "net.antelle.keeweb",
        "org.keepassx.password",
        "com.apple.security.pboard",
    ]

    struct Evaluation {
        let shouldSkip: Bool
        let reason: String?
    }

    static func evaluate(
        pasteboard: NSPasteboard,
        settings: AppSettings,
        frontmostApp: NSRunningApplication?
    ) -> Evaluation {
        if settings.respectConcealedPasteboard {
            if let reason = concealedReason(on: pasteboard) {
                return Evaluation(shouldSkip: true, reason: reason)
            }
        }

        if settings.excludeBySourceApp {
            if let bundleID = frontmostApp?.bundleIdentifier,
               isExcludedBundleID(bundleID, settings: settings) {
                let name = frontmostApp?.localizedName ?? bundleID
                return Evaluation(
                    shouldSkip: true,
                    reason: "Source app excluded: \(name)"
                )
            }
        }

        return Evaluation(shouldSkip: false, reason: nil)
    }

    static func isExcludedBundleID(_ bundleID: String, settings: AppSettings) -> Bool {
        let normalized = bundleID.lowercased()
        return settings.excludedBundleIDs.contains { excluded in
            let e = excluded.lowercased()
            return normalized == e || normalized.hasPrefix(e + ".")
        }
    }

    private static func concealedReason(on pasteboard: NSPasteboard) -> String? {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))

        if types.contains(concealedType) {
            return "Pasteboard marked concealed (password managers)"
        }
        if types.contains(transientType) {
            return "Pasteboard marked transient"
        }
        if types.contains(autoGeneratedType) {
            return "Pasteboard marked auto-generated"
        }

        for hint in sensitiveTypeHints where types.contains(hint) {
            return "Sensitive pasteboard type: \(hint)"
        }

        // Some managers put a non-empty value under ConcealedType even when listed oddly
        if pasteboard.string(forType: NSPasteboard.PasteboardType(concealedType)) != nil {
            return "Concealed pasteboard payload present"
        }

        return nil
    }

    /// Friendly list for Settings UI.
    static let knownPasswordManagerCatalog: [(name: String, bundleID: String)] = [
        ("1Password", "com.1password.1password"),
        ("1Password 7", "com.agilebits.onepassword7"),
        ("Bitwarden", "com.bitwarden.desktop"),
        ("LastPass", "com.lastpass.LastPass"),
        ("KeePassXC", "org.keepassx.keepassxc"),
        ("Dashlane", "com.dashlane.dashlanephonefinal"),
        ("Enpass", "in.sinew.Enpass-Desktop"),
        ("RoboForm", "com.SiberSystems.RoboForm"),
        ("Strongbox", "com.markmcguill.strongbox"),
        ("Proton Pass", "me.proton.pass.electron"),
        ("NordPass", "com.nordsec.nordpass"),
        ("Keeper", "com.keepersecurity.KeeperDesktop"),
        ("Keychain Access", "com.apple.keychainaccess"),
        ("Passwords (macOS)", "com.apple.Passwords"),
    ]
}
